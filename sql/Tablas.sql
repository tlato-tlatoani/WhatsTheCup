USE WTC;


CREATE TABLE CATEGORIA (
ID_CATEGORIA INT AUTO_INCREMENT NOT NULL PRIMARY KEY,
NOMBRE VARCHAR (30) NOT NULL

);

CREATE TABLE PUBLICACION (
ID_PUBLICACION INT AUTO_INCREMENT NOT NULL PRIMARY KEY,
TITULO VARCHAR (50) NOT NULL,
CONTENIDO TEXT NOT NULL,
FECHA_APROBACION DATE NOT NULL,
FECHA_PUBLICACION DATE NOT NULL,
ESTATUS ENUM ('APROBADA', 'RECHAZADA'),
MULTIMEDIA INT,
USUARIO INT,
MUNDIAL INT,
CATEGORIA INT,

FOREIGN KEY (USUARIO) REFERENCES USUARIO (ID_USUARIO),
FOREIGN KEY (MULTIMEDIA) REFERENCES MULTIMEDIA (ID_MULTIMEDIA),
FOREIGN KEY (MUNDIAL) REFERENCES MUNDIAL  (ID_MUNDIAL),
FOREIGN KEY (CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA)
);

CREATE TABLE COMENTARIOS (
ID_COMENTARIO INT AUTO_INCREMENT NOT NULL PRIMARY KEY,
CONTENIDO TEXT NOT NULL,
USUARIO INT NOT NULL,
PUBLICACION INT NOT NULL,

FOREIGN KEY (USUARIO) REFERENCES USUARIO (ID_USUARIO),
FOREIGN KEY (PUBLICACION) REFERENCES PUBLICACION (ID_PUBLICACION)
);


CREATE TABLE LIKES (
USUARIO INT NOT NULL,
PUBLICACION INT NOT NULL,

FOREIGN KEY (USUARIO) REFERENCES USUARIO (ID_USUARIO),
FOREIGN KEY (PUBLICACION) REFERENCES PUBLICACION (ID_PUBLICACION),
PRIMARY KEY (USUARIO, PUBLICACION)

);

